/**
 * Writes the current package version into `example/src/version.generated.ts` so the
 * example can display it without a runtime `fetch` (which would not resolve on a
 * static deploy). Run as the first step of the `example:*` build scripts.
 */
import { readFileSync, writeFileSync } from "node:fs";

const { version } = JSON.parse(
	readFileSync(new URL("../package.json", import.meta.url), "utf8"),
) as { version: string };

const out =
	`// AUTO-GENERATED by scripts/gen-example-version.ts — do not edit.\n` +
	`export const VERSION = ${JSON.stringify(version)};\n`;

writeFileSync(new URL("../example/src/version.generated.ts", import.meta.url), out);
console.log(`example version → ${version}`);
